import { useState } from "react";
import { Link } from "react-router-dom";
import { favoriteRecipe, saveRecipe } from "../../api/endpoints";
import type { Recipe } from "../../api/types";
import { useToast } from "../Toast";
import { errorMessage } from "../FormError";
import { Badge, Card } from "../ui";

export function RecipeView({
  recipe, onSaved, onDeleted,
}: {
  recipe: Recipe;
  onSaved: (next: Recipe) => void;
  onDeleted: () => void;
}) {
  const toast = useToast();
  const [busy, setBusy] = useState<"save" | "favorite" | null>(null);

  async function doSave() {
    setBusy("save");
    try {
      onSaved(await saveRecipe(recipe.id));
      toast.success("Recipe saved.");
    } catch (err) {
      toast.error(errorMessage(err));
    } finally {
      setBusy(null);
    }
  }
  async function doFavorite(next: boolean) {
    setBusy("favorite");
    try {
      onSaved(await favoriteRecipe(recipe.id, next));
    } catch (err) {
      toast.error(errorMessage(err));
    } finally {
      setBusy(null);
    }
  }
  void onDeleted;

  return (
    <Card title={recipe.title} headingId={`recipe-${recipe.id}`}>
      <p className="small-text muted">
        {recipe.description}
      </p>
      <p className="small-text">
        <Badge tone={recipe.status === "saved" ? "ok" : "neutral"}>
          {recipe.status === "saved" ? "Saved" : "Suggestion (not saved yet)"}
        </Badge>
        {" "}
        <Badge>{recipe.servings} servings</Badge>
        {recipe.total_minutes !== null && <>{" "}<Badge>{recipe.total_minutes} min total</Badge></>}
        {recipe.provider && <>{" "}<Badge>Generated by {recipe.provider.model}</Badge></>}
      </p>

      <p className="alert info" role="note">{recipe.context_note}</p>
      {recipe.allergen_warnings.length > 0 && (
        <div className="alert warn">
          <p><strong>Allergen and cross-contact warnings</strong></p>
          <ul className="plain-list">{recipe.allergen_warnings.map((w, i) => <li key={i}>{w}</li>)}</ul>
        </div>
      )}
      {recipe.dietary_tags.length > 0 && (
        <p className="small-text">Tags: {recipe.dietary_tags.join(", ")}. <span className="muted">{recipe.allergy_note}</span></p>
      )}

      {recipe.equipment.length > 0 && (
        <>
          <h3>Equipment</h3>
          <ul className="plain-list">{recipe.equipment.map((e, i) => <li key={i}>{e}</li>)}</ul>
        </>
      )}

      <h3>Ingredients</h3>
      <ul className="plain-list">
        {recipe.ingredients.map((ing, i) => (
          <li key={i}>
            {ing.quantity !== null && <strong>{ing.quantity} {ing.unit ?? ""}</strong>}{" "}
            {ing.name}
            {ing.note ? <> <span className="muted">({ing.note})</span></> : null}
            {ing.optional ? <> <em className="muted">— optional</em></> : null}
          </li>
        ))}
      </ul>

      <h3>Method</h3>
      <ol className="plain-list">
        {recipe.steps.map((s) => (
          <li key={s.number}>
            {s.instruction}
            {s.duration_minutes !== null && <> <span className="muted">({s.duration_minutes} min)</span></>}
          </li>
        ))}
      </ol>

      {recipe.substitutions.length > 0 && (
        <>
          <h3>Substitutions</h3>
          <ul className="plain-list">
            {recipe.substitutions.map((s, i) => (
              <li key={i}>{s.ingredient} → {s.alternative}{s.note ? ` (${s.note})` : ""}</li>
            ))}
          </ul>
        </>
      )}

      {recipe.safety_notes.length > 0 && (
        <>
          <h3>Safety notes</h3>
          <ul className="plain-list">{recipe.safety_notes.map((n, i) => <li key={i}>{n}</li>)}</ul>
        </>
      )}
      {recipe.beginner_notes.length > 0 && (
        <>
          <h3>Beginner notes</h3>
          <ul className="plain-list">{recipe.beginner_notes.map((n, i) => <li key={i}>{n}</li>)}</ul>
        </>
      )}
      {recipe.tips.length > 0 && (
        <>
          <h3>Tips</h3>
          <ul className="plain-list">{recipe.tips.map((t, i) => <li key={i}>{t}</li>)}</ul>
        </>
      )}

      {recipe.nutrition ? (
        <section aria-label="Nutrition (verified)">
          <h3>Nutrition (linked to verified food data)</h3>
          <p className="small-text muted">{recipe.nutrition.basis}. {recipe.nutrition.note}</p>
          <table className="nutrient-table compact">
            <caption className="visually-hidden">Per serving</caption>
            <tbody>
              {Object.values(recipe.nutrition.per_serving).map((t) =>
                t.low === null || t.high === null ? null : (
                  <tr key={t.key}>
                    <th scope="row">{t.label}</th>
                    <td>{t.low === t.high ? `${t.low} ${t.unit}` : `${t.low}–${t.high} ${t.unit}`}</td>
                  </tr>
                ),
              )}
            </tbody>
          </table>
          <p className="small-text">
            <Link to={`/recipes/${recipe.id}`}>Open this recipe</Link> for the full nutrient breakdown and to link more ingredients.
          </p>
        </section>
      ) : (
        <p className="small-text muted">
          No nutrition numbers are shown: the model does not estimate them. Open the saved recipe to link
          ingredients to verified food data.
        </p>
      )}

      <div className="stacked-actions">
        {recipe.status === "suggested" && (
          <button type="button" onClick={doSave} disabled={busy !== null}>
            {busy === "save" ? "Saving…" : "Save this recipe"}
          </button>
        )}
        <button
          type="button"
          className="secondary"
          onClick={() => doFavorite(!recipe.favorite)}
          disabled={busy !== null}
        >
          {recipe.favorite ? "Unfavorite" : "Favorite"}
        </button>
        <Link className="button-link secondary" to={`/recipes/${recipe.id}`}>Open</Link>
      </div>
    </Card>
  );
}