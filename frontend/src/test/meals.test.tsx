import { screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { CALC, MEAL, mealPage, foodRoutes } from "./food-fixtures";
import { errorBody, json, mockApi, renderApp } from "./helpers";

const photo = () => new Response(new Uint8Array([1]), { headers: { "Content-Type": "image/png" } });

describe("meal log", () => {
  it("shows an honest empty state", async () => {
    mockApi(foodRoutes({ "GET /meals?page=1&page_size=10": () => json(200, mealPage([])) }));
    renderApp("/meals");
    expect(await screen.findByText("No meals saved yet")).toBeInTheDocument();
  });

  it("lists meals with calories marked partial when data was missing", async () => {
    mockApi(foodRoutes({ "GET /meals?page=1&page_size=10": () => json(200, mealPage()) }));
    renderApp("/meals");
    const link = await screen.findByRole("link", { name: "Apple, Rice" });
    expect(link).toHaveAttribute("href", "/meals/meal1");
    expect(screen.getByText("78 kcal (partial)")).toBeInTheDocument();
  });

  it("says calories are unavailable rather than showing zero", async () => {
    const m = { ...MEAL, calories: { low: null, high: null, complete: false } };
    mockApi(foodRoutes({ "GET /meals?page=1&page_size=10": () => json(200, mealPage([m])) }));
    renderApp("/meals");
    expect(await screen.findByText("Calories not available")).toBeInTheDocument();
  });

  it("filters by meal category on the server", async () => {
    const { calls } = mockApi(foodRoutes({
      "GET /meals?page=1&page_size=10": () => json(200, mealPage()),
      "GET /meals?page=1&page_size=10&category=dinner": () => json(200, mealPage([])),
    }));
    const user = userEvent.setup();
    renderApp("/meals");
    await screen.findByRole("link", { name: "Apple, Rice" });
    await user.selectOptions(screen.getByLabelText("Meal"), "dinner");
    expect(await screen.findByText("No meals in this category")).toBeInTheDocument();
    expect(calls.some((c) => c.key.endsWith("category=dinner"))).toBe(true);
  });

  it("deletes only after confirmation", async () => {
    let deleted = false;
    const { calls } = mockApi(foodRoutes({
      "GET /meals?page=1&page_size=10": () => json(200, mealPage(deleted ? [] : [MEAL])),
      "DELETE /meals/meal1": () => { deleted = true; return json(204); },
    }));
    const user = userEvent.setup();
    renderApp("/meals");
    await user.click(await screen.findByRole("button", { name: "Delete Apple, Rice" }));
    const dialog = screen.getByRole("dialog");
    await user.click(within(dialog).getByRole("button", { name: "Cancel" }));
    expect(calls.some((c) => c.key.startsWith("DELETE"))).toBe(false);

    await user.click(screen.getByRole("button", { name: "Delete Apple, Rice" }));
    await user.click(within(screen.getByRole("dialog")).getByRole("button", { name: "Delete" }));
    expect(await screen.findByText("Meal deleted.")).toBeInTheDocument();
    expect(await screen.findByText("No meals saved yet")).toBeInTheDocument();
  });

  it("surfaces a failed delete without removing the row", async () => {
    mockApi(foodRoutes({
      "GET /meals?page=1&page_size=10": () => json(200, mealPage()),
      "DELETE /meals/meal1": () => json(404, errorBody("meal_not_found", "Meal not found.")),
    }));
    const user = userEvent.setup();
    renderApp("/meals");
    await user.click(await screen.findByRole("button", { name: "Delete Apple, Rice" }));
    await user.click(within(screen.getByRole("dialog")).getByRole("button", { name: "Delete" }));
    expect(await screen.findByText("Meal not found.")).toBeInTheDocument();
  });
});

describe("meal detail and edit", () => {
  const detailRoutes = (over = {}) => foodRoutes({
    "GET /meals/meal1": () => json(200, MEAL),
    "GET /media/m1/content": photo,
    ...over,
  });

  it("shows the saved audit: sources, gaps, and model output labelled as model-generated", async () => {
    mockApi(detailRoutes());
    renderApp("/meals/meal1");
    expect(await screen.findByRole("heading", { name: "Apple, Rice" })).toBeInTheDocument();
    expect(screen.getByText("with tea")).toBeInTheDocument();
    expect(screen.getByText(/ID 171688/)).toBeInTheDocument();
    expect(screen.getByText(/Disclaimer|Estimates only/)).toBeInTheDocument();
    const obs = screen.getByRole("heading", { name: "What the photo model suggested" }).closest("section")!;
    expect(obs).toHaveTextContent("Model-generated by “llava-test”");
    expect(obs).toHaveTextContent("it is not nutrition data");
    expect(obs).toHaveTextContent("Apple (model unsure)");
    expect(await screen.findByRole("img", { name: "Photo of this meal" })).toBeInTheDocument();
  });

  it("omits the model section for a meal entered by hand", async () => {
    const manual = { ...MEAL, media_id: null, result: { ...MEAL.result, model_observations: null } };
    mockApi(detailRoutes({ "GET /meals/meal1": () => json(200, manual) }));
    renderApp("/meals/meal1");
    await screen.findByRole("heading", { name: "Apple, Rice" });
    expect(screen.queryByText("What the photo model suggested")).not.toBeInTheDocument();
  });

  it("shows a friendly page for a meal that is missing or not yours", async () => {
    mockApi(foodRoutes({ "GET /meals/nope": () => json(404, errorBody("meal_not_found", "Meal not found.")) }));
    renderApp("/meals/nope");
    expect(await screen.findByText("Meal not found")).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "Back to the meal log" })).toBeInTheDocument();
  });

  it("deletes from the detail page after confirmation and returns to the list", async () => {
    mockApi(detailRoutes({
      "DELETE /meals/meal1": () => json(204),
      "GET /meals?page=1&page_size=10": () => json(200, mealPage([])),
    }));
    const user = userEvent.setup();
    renderApp("/meals/meal1");
    await user.click(await screen.findByRole("button", { name: "Delete" }));
    await user.click(within(screen.getByRole("dialog")).getByRole("button", { name: "Delete" }));
    expect(await screen.findByText("No meals saved yet")).toBeInTheDocument();
  });

  it("edits a saved meal, sending item ids and the revision it was based on", async () => {
    const updated = { ...MEAL, revision: 2 };
    const { calls } = mockApi(detailRoutes({
      "POST /food/calculate": () => json(200, CALC),
      "PUT /meals/meal1": () => json(200, updated),
    }));
    const user = userEvent.setup();
    renderApp("/meals/meal1/edit");
    expect(await screen.findByRole("heading", { name: "Edit meal" })).toBeInTheDocument();
    expect(screen.getByLabelText("Food 1")).toHaveValue("Apple");
    expect(screen.getByLabelText("Weight of Apple")).toHaveValue("150");

    await user.clear(screen.getByLabelText("Weight of Apple"));
    await user.type(screen.getByLabelText("Weight of Apple"), "200");
    await user.click(screen.getByRole("button", { name: "Calculate nutrition" }));
    await user.click(await screen.findByRole("button", { name: "Save changes" }));
    expect(await screen.findByText("Meal updated.")).toBeInTheDocument();

    const calc = calls.find((c) => c.key === "POST /food/calculate")?.body as { meal_id: string; items: Record<string, unknown>[] };
    expect(calc.meal_id).toBe("meal1");
    expect(calc.items[0]).toMatchObject({ item_id: "i1", name: "Apple", portion: { kind: "weight", amount: 200, unit: "g" } });
    expect(calc.items[0]).not.toHaveProperty("food_ref"); // keeps the saved source record
    const put = calls.find((c) => c.key === "PUT /meals/meal1")?.body as Record<string, unknown>;
    expect(put).toMatchObject({ expected_revision: 1, category: "lunch", media_id: "m1" });
  });

  it("explains a revision conflict instead of overwriting", async () => {
    mockApi(detailRoutes({
      "POST /food/calculate": () => json(200, CALC),
      "PUT /meals/meal1": () => json(409, errorBody("meal_revision_conflict", "This meal was changed somewhere else. Reload it and try again.")),
    }));
    const user = userEvent.setup();
    renderApp("/meals/meal1/edit");
    await screen.findByRole("heading", { name: "Edit meal" });
    await user.click(screen.getByRole("button", { name: "Calculate nutrition" }));
    await user.click(await screen.findByRole("button", { name: "Save changes" }));
    expect(await screen.findByText(/changed somewhere else/)).toBeInTheDocument();
  });

  it("links food-recognition history entries to the meal", async () => {
    mockApi(foodRoutes({
      "GET /history?page=1&page_size=10": () => json(200, mealPage([{
        id: "meal1", module: "food_recognition", status: "completed", title: "Lunch: Apple, Rice",
        summary: "s", media_id: null, created_at: "2026-10-25T08:00:00Z",
      }])),
      "GET /modules": () => json(200, [{ key: "food_recognition", title: "Food recognition", description: "d", available: true }]),
    }));
    renderApp("/history");
    expect(await screen.findByRole("link", { name: "Lunch: Apple, Rice" })).toHaveAttribute("href", "/meals/meal1");
  });
});
