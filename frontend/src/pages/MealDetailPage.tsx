import { useCallback, useState } from "react";
import { Link, useNavigate, useParams } from "react-router-dom";
import { deleteMeal, getMeal } from "../api/endpoints";
import { ApiError } from "../api/client";
import { AuthImage } from "../components/AuthImage";
import { ConfirmDialog } from "../components/ConfirmDialog";
import { draftFromSaved } from "../components/food/drafts";
import { MealBuilder } from "../components/food/MealBuilder";
import { NutritionResults } from "../components/food/NutritionResults";
import { errorMessage } from "../components/FormError";
import { useToast } from "../components/Toast";
import { Card, EmptyState, ErrorState, Loading, PageHeader } from "../components/ui";
import { useResource } from "../hooks/useResource";
import { categoryLabel } from "../lib/food";
import { formatDate } from "../lib/format";
import type { MealDetail } from "../api/types";

export function MealDetailPage() {
  const { id = "" } = useParams<{ id: string }>();
  const navigate = useNavigate();
  const toast = useToast();
  const [confirming, setConfirming] = useState(false);
  const meal = useResource(useCallback(() => getMeal(id), [id]));

  async function remove() {
    try {
      await deleteMeal(id);
      toast.success("Meal deleted.");
      navigate("/meals");
    } catch (err) {
      toast.error(errorMessage(err));
    } finally {
      setConfirming(false);
    }
  }

  if (meal.error instanceof ApiError && meal.error.status === 404) {
    return <EmptyState title="Meal not found" description="It may have been deleted."
      action={<Link to="/meals">Back to the meal log</Link>} />;
  }
  if (meal.error) return <ErrorState error={meal.error} onRetry={meal.reload} />;
  if (!meal.data) return <Loading />;
  const m = meal.data;
  const obs = m.result.model_observations;

  return (
    <>
      <PageHeader title={m.items_label}
        description={<>{categoryLabel(m.category)} · <time dateTime={m.eaten_at}>{formatDate(m.eaten_at)}</time></>}
        actions={<>
          <Link className="button-link secondary" to={`/meals/${m.id}/edit`}>Edit</Link>
          <button type="button" className="secondary" onClick={() => setConfirming(true)}>Delete</button>
        </>} />
      {m.notes && <Card title="Notes" headingId="notes-h"><p>{m.notes}</p></Card>}
      {m.media_id && (
        <Card title="Photo" headingId="photo-h"><AuthImage mediaId={m.media_id} alt="Photo of this meal" className="detail-photo" /></Card>
      )}
      <Card title="Nutrition" headingId="nutrition-h"><NutritionResults calc={m.result} /></Card>
      {obs && (
        <Card title="What the photo model suggested" headingId="obs-h">
          <p className="small-text muted">
            Model-generated by “{obs.provider.model}” on <time dateTime={obs.generated_at}>{formatDate(obs.generated_at)}</time>.
            Kept for the record; it is not nutrition data. {obs.uncertainty_note}
          </p>
          {obs.items.length === 0 ? <p>The model did not name any foods.</p> : (
            <ul className="plain-list">
              {obs.items.map((o) => (
                <li key={o.observed_id}>{o.name}{o.ambiguous ? " (model unsure)" : ""}{o.description ? ` — ${o.description}` : ""}</li>
              ))}
            </ul>
          )}
        </Card>
      )}
      <p><Link to="/meals">← All meals</Link></p>
      <ConfirmDialog open={confirming} title="Delete this meal?"
        message="This meal and its saved analysis will be permanently deleted."
        confirmLabel="Delete" onConfirm={remove} onCancel={() => setConfirming(false)} />
    </>
  );
}

function MealEditor({ meal }: { meal: MealDetail }) {
  return (
    <>
      <PageHeader title="Edit meal" description="Change foods, portions or details. Totals are recalculated from the data sources." />
      <MealBuilder meal={meal} initialItems={meal.result.items.map(draftFromSaved)} />
      <p><Link to={`/meals/${meal.id}`}>← Cancel and go back</Link></p>
    </>
  );
}

export function MealEditPage() {
  const { id = "" } = useParams<{ id: string }>();
  const meal = useResource(useCallback(() => getMeal(id), [id]));
  if (meal.error) return <ErrorState error={meal.error} onRetry={meal.reload} />;
  if (!meal.data) return <Loading />;
  return <MealEditor meal={meal.data} />;
}
